# 判据不是「重要不重要」，是**这个数是怎么来的**：
# 回放扫出来的阈值（sl / tp / 持仓上限 / 快查节拍 / zone_edge…）让人在界面上
# 随手拖，拖出来的就是噪声——227 笔反事实回放里所有放松版本都更差，tp 扫描
# 是锯齿。这类「有证据的数」只能随代码走，改它要带上新证据。
# 反过来「这单投多大、多久问一次、要不要真下单、亏多少就停」是仓位与节奏，
# 本来就该按当下的账户和心情调。
